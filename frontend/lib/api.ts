import snapshot from "./demo-snapshot.json";
import type { ChatReply, Cohort, Factor, Overview } from "./types";

const API = (process.env.NEXT_PUBLIC_API_URL || "").replace(/\/$/, "");
const snap = snapshot as unknown as {
  regions: string[];
  overview: Record<string, Overview>;
  cohorts: Record<string, Cohort[]>;
  factors: Factor[];
};

async function get<T>(path: string, fallback: () => T): Promise<{ data: T; live: boolean }> {
  if (!API) return { data: fallback(), live: false };
  try {
    const res = await fetch(`${API}${path}`, { cache: "no-store" });
    if (!res.ok) throw new Error(res.statusText);
    return { data: (await res.json()) as T, live: true };
  } catch {
    return { data: fallback(), live: false };
  }
}

const snapMonths = (m: number) => ([3, 6, 12].includes(m) ? m : 12);
const regionParam = (r: string) => (r && r !== "All" ? `&region=${encodeURIComponent(r)}` : "");

export const api = {
  hasBackend: Boolean(API),

  regions: () => get<string[]>("/api/regions", () => snap.regions),

  overview: (months: number, region: string) =>
    get<Overview>(`/api/overview?months=${months}${regionParam(region)}`, () => snap.overview[`${snapMonths(months)}|${region || "All"}`]),

  cohorts: (region: string) =>
    get<Cohort[]>(`/api/cohorts?x=1${regionParam(region)}`, () => snap.cohorts[region || "All"]),

  factors: () => get<Factor[]>("/api/market-factors", () => snap.factors),

  async chat(messages: { role: "user" | "assistant"; content: string }[]): Promise<ChatReply> {
    if (!API) return offlineReply();
    try {
      const res = await fetch(`${API}/api/chat`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ messages }),
      });
      if (!res.ok) {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.detail || `The analyst returned an error (${res.status}).`);
      }
      return (await res.json()) as ChatReply;
    } catch (e) {
      if (e instanceof TypeError) return offlineReply();
      throw e;
    }
  },

  async report(body: {
    format: "pptx" | "docx" | "pdf";
    title: string;
    months: number;
    region: string;
    sections: string[];
    weights?: Record<string, number>;
  }): Promise<{ blob: Blob; filename: string }> {
    if (!API) throw new Error("Reports are generated by the MarketLens API. Start the backend and set NEXT_PUBLIC_API_URL.");
    let res: Response;
    try {
      res = await fetch(`${API}/api/reports`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
    } catch {
      throw new Error(`Can't reach the API at ${API}. Check that the backend is running.`);
    }
    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.detail || `Report generation failed (${res.status}).`);
    }
    const cd = res.headers.get("Content-Disposition") || "";
    const filename = /filename="([^"]+)"/.exec(cd)?.[1] || `marketlens-report.${body.format}`;
    return { blob: await res.blob(), filename };
  },
};

function offlineReply(): ChatReply {
  return {
    answer:
      "The AI analyst runs on the MarketLens API, which isn't connected right now.\n\n" +
      "To turn it on:\n1. Start the backend: `uvicorn app.main:app --reload`\n" +
      "2. Set `NEXT_PUBLIC_API_URL=http://localhost:8000` in `frontend/.env.local`\n" +
      "3. Add `ANTHROPIC_API_KEY` to `backend/.env` for full AI answers",
    queries: [],
    chart: null,
    mode: "offline",
  };
}
